"""Write the route registration methods of `Router` and `App` from one table of
options, so a new route option is one row here rather than an edit to every
verb. Usage, from the repository root: python scripts/gen_verbs.py"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

# (name, type, default); a default of None makes the parameter optional (`name?`).
OPTIONS = [
    ("summary", "String", '""'),
    ("description", "String", '""'),
    ("tags", "Array[String]", "[]"),
    ("deprecated", "Bool", "false"),
    ("operation_id", "String", '""'),
    ("status_code", "Int", None),
    ("responses", "Array[@endpoint.ResponseSpec]", "[]"),
    ("name", "String", '""'),
    ("endpoint", "@endpoint.Endpoint", None),
    ("security", "Array[@security.SecurityRequirement]", "[]"),
    ("dependencies", "Array[String]", "[]"),
    ("include_in_schema", "Bool", "true"),
    ("validate", "Bool", "true"),
    ("openapi_extra", "Json", None),
    ("callbacks", "Array[@route.Route]", "[]"),
    ("hoops", "Array[@route.Hoop]", "[]"),
]

VERBS = [
    ("get", "Get", "GET"),
    ("post", "Post", "POST"),
    ("put", "Put", "PUT"),
    ("patch", "Patch", "PATCH"),
    ("delete", "Delete", "DELETE"),
    ("options", "Options", "OPTIONS"),
    ("head", "Head", "HEAD"),
    ("trace", "Trace", "TRACE"),
]

HEADER = "// Generated by scripts/gen_verbs.py. Do not edit by hand.\n"

ROUTE_DOC = """/// Register a route for an explicit method. An optional `endpoint` descriptor
/// makes the route fully typed (its parameters, request body, and responses
/// surface in the OpenAPI document and drive validation); `security` attaches
/// per-operation requirements (emitted as OpenAPI `security` and enforced before
/// the handler when their scheme has an enforcer); `dependencies` names provider
/// keys resolved through the app's container (`App::depends`) before the handler
/// and torn down after it, whatever the handler did.
///
/// The rest describe the operation: `summary` and `description` are its prose,
/// `operation_id` the stable handle client generators name their method after,
/// `status_code` the status its success response is documented under,
/// `responses` further documented responses, `name` the handle `App::url_for`
/// resolves, `openapi_extra` a fragment merged over the generated operation
/// object, and `callbacks` the requests this operation makes back to its caller,
/// written as routes whose paths are runtime expressions — the same keyword
/// arguments FastAPI's path operations take. `hoops` wrap this one route, inside
/// any its routers put around it."""

STREAM_DOC = """/// Register a streaming route (← a FastAPI path operation returning a
/// `StreamingResponse`). The handler's chunks reach the client as separate body
/// events, so a long or open-ended reply starts arriving before it is finished.
///
/// A stream is only streamed as far as the app can honestly keep it one: a
/// middleware that rewrites the body — `gzip` does — collapses the reply to a
/// single chunk. Everything else about the route is ordinary; it documents,
/// validates and enforces security exactly as `route` does."""


def params(owner):
    out = []
    for name, typ, default in OPTIONS:
        if owner == "Router":
            typ = typ.replace("@route.", "")
        out.append(f"  {name}? : {typ}," if default is None else f"  {name}~ : {typ} = {default},")
    return "\n".join(out)


def forward():
    return "\n".join(f"    {name}?," if default is None else f"    {name}~," for name, _, default in OPTIONS)


def fields():
    return "\n".join(f"    {name}," for name, _, _ in OPTIONS)


def method(owner, name, doc, extra_params, handler_type, body):
    return f"""///|
{doc}
pub fn {owner}::{name}(
  self : {owner},
{extra_params}
  handler : {handler_type},
{params(owner)}
) -> Unit {{
{body}
}}
"""


def router_file():
    parts = [HEADER]
    parts.append(method(
        "Router", "route", ROUTE_DOC.replace("Register a route", "Register a route on the router"),
        "  verb : Method,\n  path : String,", "ApiHandler",
        f"  self.routes.push({{\n    verb,\n    path,\n    pattern: Pattern::parse(path),\n    run: ctx => Buffered(handler(ctx)),\n{fields()}\n  }})"))
    parts.append(method(
        "Router", "route_stream", STREAM_DOC, "  verb : Method,\n  path : String,", "StreamHandler",
        f"  self.routes.push({{\n    verb,\n    path,\n    pattern: Pattern::parse(path),\n    run: ctx => Streamed(handler(ctx)),\n{fields()}\n  }})"))
    parts.append(method(
        "Router", "stream",
        "/// Register a streaming `GET` route — the verb a stream is nearly always read\n/// over, and what an SSE endpoint is. A shorthand for `route_stream(Get, ...)`.",
        "  path : String,", "StreamHandler",
        f"  self.route_stream(\n    Get,\n    path,\n    handler,\n{forward()}\n  )"))
    for verb, ctor, upper in VERBS:
        parts.append(method(
            "Router", verb, f"/// Register a `{upper}` route. A shorthand for `route({ctor}, ...)`.",
            "  path : String,", "ApiHandler",
            f"  self.route(\n    {ctor},\n    path,\n    handler,\n{forward()}\n  )"))
    return "\n".join(parts)


def app_file():
    parts = [HEADER]
    parts.append(method(
        "App", "route", ROUTE_DOC, "  verb : @route.Method,\n  path : String,", "@route.ApiHandler",
        f"  self.router.route(\n    verb,\n    path,\n    handler,\n{forward()}\n  )"))
    parts.append(method(
        "App", "route_stream", STREAM_DOC, "  verb : @route.Method,\n  path : String,", "@route.StreamHandler",
        f"  self.router.route_stream(\n    verb,\n    path,\n    handler,\n{forward()}\n  )"))
    parts.append(method(
        "App", "stream",
        "/// Register a streaming `GET` route — the verb a stream is nearly always read\n/// over, and what an SSE endpoint is. A shorthand for `route_stream(Get, ...)`.",
        "  path : String,", "@route.StreamHandler",
        f"  self.router.stream(\n    path,\n    handler,\n{forward()}\n  )"))
    for verb, ctor, upper in VERBS:
        parts.append(method(
            "App", verb, f"/// Register a `{upper}` route. A shorthand for `route({ctor}, ...)`.",
            "  path : String,", "@route.ApiHandler",
            f"  self.router.{verb}(\n    path,\n    handler,\n{forward()}\n  )"))
    return "\n".join(parts)


(ROOT / "src" / "route" / "verbs.mbt").write_text(router_file(), encoding="utf-8", newline="\n")
(ROOT / "src" / "verbs.mbt").write_text(app_file(), encoding="utf-8", newline="\n")
print("wrote src/route/verbs.mbt and src/verbs.mbt")
